"""`exo p0` (D-32) y `exo codeowners` (F5, ADR-0014)."""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from exo import _meta
from exo.commands._output import emit_json, error
from exo.core import config
from exo.governance import p0


def register(sub: argparse._SubParsersAction) -> None:
    gate = sub.add_parser(
        "p0",
        help="minimum regression gate: scanner, input validation and active git hooks",
        description="Prints `P0 GATE: PASSED (3/3)` and exits with 0 when the three pass.",
    )
    gate.add_argument("--project", type=Path, default=Path("."), help="project root")
    gate.add_argument("--json", action="store_true", help="JSON output")
    gate.set_defaults(handler=_p0)

    owners = sub.add_parser(
        "codeowners",
        help="print a CODEOWNERS file from governance.roles",
        description=(
            "The tech_lead role owns the specs folder and the engine folder. The engine does not "
            "check roles: the host's branch protection with code-owner review makes it effective "
            "(see the ci-and-review contract)."
        ),
    )
    owners.add_argument("--project", type=Path, default=Path("."), help="project root")
    owners.set_defaults(handler=_codeowners)


def _p0(args: argparse.Namespace) -> int:
    results = p0.run(args.project)
    passed = sum(r.ok for r in results)
    total = len(results)
    verdict = "PASSED" if passed == total else "FAILED"
    if args.json:
        emit_json(
            {
                "passed": passed,
                "total": total,
                "verdict": verdict,
                "checks": [{"name": r.name, "ok": r.ok, "detail": r.detail} for r in results],
            }
        )
    else:
        for index, item in enumerate(results, start=1):
            state = "PASSED" if item.ok else "FAILED"
            print(f"P0 {index}/{total} {item.name}: {state} ({item.detail})")
        print(f"=== P0 GATE: {verdict} ({passed}/{total}) ===")
    return 0 if passed == total else 1


_AGENT_AND_HOOK_PATHS = (
    "AGENTS.md",
    "CLAUDE.md",
    ".claude/",
    ".agents/",
    ".mcp.json",
    ".husky/",
    ".pre-commit-config.yaml",
    ".gitattributes",
)


def _codeowners(args: argparse.Namespace) -> int:
    cfg = config.load(args.project).config
    leads = cfg["governance"]["roles"].get("tech_lead") or []
    if not leads:
        return error(
            f"governance.roles.tech_lead is empty in {_meta.PROJECT_DIR}/config.json: add the "
            "handles or emails of the tech leads first"
        )
    people = " ".join(leads)
    specs_dir = cfg["specs_dir"].strip("/")
    lines = [
        f"# Generated by `{_meta.NAME} codeowners` from governance.roles in "
        f"{_meta.PROJECT_DIR}/config.json.",
        "# Effective only with the host's branch protection requiring code-owner review.",
        f"/{specs_dir}/ {people}",
        f"/{_meta.PROJECT_DIR}/ {people}",
        # Lo que leen los agentes (reglas, skills, subagentes, permisos, MCP) y lo que ejecuta
        # git: un cambio ahí cambia lo que hace cada clon (threat model, TM-16 y TM-39).
        *(f"/{path} {people}" for path in _AGENT_AND_HOOK_PATHS),
    ]
    sys.stdout.write("\n".join(lines) + "\n")
    return 0
