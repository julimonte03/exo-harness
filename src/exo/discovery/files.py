RECOVERED_ADR = "*-recovered-*.md"
# Lo que produce o gestiona el propio flujo: se excluye y no se cuenta.
_UNCOUNTED = frozenset({"engine", "specs", "recovered"})


@dataclass(frozen=True)
class SourceFile:
    path: str  # relativa al proyecto, con /
    size: int  # bytes con LF (los de credenciales, que no se leen: el tamaño en disco)
    sha: str  # vacío para los archivos de credenciales, que no se leen
    language: str | None
    category: str  # code | test | migration | sensitive | other
    sensitive: bool = False
    lines: int = 0


@dataclass
class FileSet:
    files: list[SourceFile] = field(default_factory=list)
    excluded: dict[str, int] = field(default_factory=dict)
    git: bool = True
    warnings: list[str] = field(default_factory=list)

    def by_category(self, category: str) -> list[SourceFile]:
        return [f for f in self.files if f.category == category]


def _generated(head: bytes) -> bool:
    """Un encabezado de archivo generado: `@generated`, o "generated" junto a "do not edit"."""
    return any(m in head for m in _GENERATED_MARKERS) or (
        b"generated" in head and b"do not edit" in head
    )


def to_lf(data: bytes) -> bytes:
    """CRLF y CR sueltos como LF: los bytes que da el mismo archivo en cualquier checkout."""
    return data.replace(b"\r\n", b"\n").replace(b"\r", b"\n")


def count_lines(data: bytes) -> int:
    """Líneas del archivo: una última línea sin salto también cuenta."""
    if not data:
        return 0
    normalized = to_lf(data)
    return normalized.count(b"\n") + (0 if normalized.endswith(b"\n") else 1)


def normalized_hash(data: bytes) -> str:
    """sha256 con CRLF y CR sueltos como LF: el mismo archivo da el mismo hash en todo SO."""
    return fsutil.sha256_bytes(to_lf(data))


def language_of(path: str) -> str | None:
    return LANGUAGES.get(PurePosixPath(path).suffix.lower())


def is_test(path: str) -> bool:
    """Las reglas de test de ADR-0015, por lenguaje."""
    parts = PurePosixPath(path).parts
    name = parts[-1]
    language = language_of(path)
    if language == "python":
        return (
            any(p in ("tests", "test") for p in parts[:-1])
            or name.startswith("test_")
            or name.endswith("_test.py")
            or name == "conftest.py"
        )
    if language in ("javascript", "typescript"):
        stem_parts = name.split(".")
        return "__tests__" in parts[:-1] or any(p in ("test", "spec") for p in stem_parts[1:-1])
    if language in ("java", "kotlin", "scala"):
        return "src/test/" in f"/{path}"
    if language == "go":
        return name.endswith("_test.go")
    return False


def is_migration(path: str) -> bool:
    parts = PurePosixPath(path).parts[:-1]
    for pattern in MIGRATION_DIRS:
        size = len(pattern)
        if any(parts[i : i + size] == pattern for i in range(len(parts) - size + 1)):
            return True
    return False


def _category(path: str, sensitive: bool) -> str:
    if sensitive:
        return "sensitive"
    if is_migration(path):
        return "migration"
    if is_test(path):
        return "test"
    return "code" if language_of(path) in CODE_LANGUAGES else "other"


def _ignored(path: str, patterns: list[str]) -> bool:
    name = PurePosixPath(path).name
    for pattern in patterns:
        target = path if "/" in pattern else name
        if fnmatch.fnmatchcase(target, pattern.rstrip("/")) or (
            pattern.endswith("/") and (path + "/").startswith(pattern)
        ):
            return True
    return False


def _engine_paths(project: Path) -> set[str]:
    """Lo que instaló el motor fuera de su carpeta (skills, subagentes, archivos creados)."""
    try:
        data = lock.read(project)
    except (lock.LockError, OSError, ValueError):
        return set()
    if data is None:
        return set()
    owned = {e.path for e in data.files if e.kind in ("file", "mirror")}
    owned |= {c.path for c in data.created if c.file}
    return owned


def _tracked(project: Path, include_untracked: bool) -> list[str] | None:
    listed = git.run(project, "ls-files", "-s", "-z")
    if not listed.ok:
        return None
    paths: list[str] = []
    for item in listed.out.split("\0"):
        if not item:
            continue
        meta, _, path = item.partition("\t")
        mode = meta.split(" ", 1)[0]
        if mode in ("100644", "100755"):  # sin symlinks (120000) ni submódulos (160000)
            paths.append(path)
    if include_untracked:
        others = git.run(project, "ls-files", "--others", "--exclude-standard", "-z")
        if others.ok:
            paths += [p for p in others.out.split("\0") if p]
    return sorted(set(paths))


def _walked(project: Path) -> list[str]:
    found: list[str] = []
    for path in fsutil.walk_files(project):
        rel = path.relative_to(project).as_posix()
        if not any(part in VENDORED_DIRS for part in PurePosixPath(rel).parts[:-1]):
            found.append(rel)
    return found


def is_recovered_adr(rel: str) -> bool:
    """Un ADR que escribió la ingeniería inversa (`<carpeta de ADRs>/*-recovered-*.md`)."""
    pure = PurePosixPath(rel)
    return pure.parent.as_posix() in ADR_DIRS and fnmatch.fnmatchcase(pure.name, RECOVERED_ADR)


def _exclusion(rel: str, specs_dir: str, engine: set[str], cfg: dict) -> str | None:
    pure = PurePosixPath(rel)
    if pure.parts[0] == _meta.PROJECT_DIR:
        return "engine"
    if pure.is_relative_to(PurePosixPath(specs_dir)):
        return "specs"
    if rel in engine:
        return "engine"
    if is_recovered_adr(rel):
        return "recovered"
    if any(part in VENDORED_DIRS for part in pure.parts[:-1]):
        return "vendored"
    if pure.name in LOCK_FILES or any(
        fnmatch.fnmatchcase(pure.name, p) for p in GENERATED_PATTERNS
    ):
        return "generated"
    if _ignored(rel, list(cfg["discovery"]["ignore"])):
        return "ignored"
    return None


def list_files(project: Path, *, include_untracked: bool = False) -> FileSet:
    project = Path(project)
    cfg = config.load(project).config
    specs_dir = cfg["specs_dir"].strip("/")
    engine = _engine_paths(project)
    result = FileSet()
    paths = _tracked(project, include_untracked)
    if paths is None:
        result.git = False
        result.warnings.append(
            "not a git repository: .gitignore is not applied, only the built-in exclusions "
            "and discovery.ignore"
        )
        paths = _walked(project)
    counts: dict[str, int] = {}
    for rel in paths:
        reason = _exclusion(rel, specs_dir, engine, cfg)
        path = project / rel
        if reason is None and not path.is_file():
            continue  # versionado pero borrado de la copia de trabajo
        if reason is None:
            sensitive = scan.is_credential_file(rel)
            if sensitive:
                result.files.append(
                    SourceFile(rel, path.stat().st_size, "", language_of(rel), "sensitive", True)
                )
                continue
            # Con CRLF un archivo ocupa como mucho el doble que con LF: lo que pasa de 2 MB
            # en disco pasa de 1 MB en cualquier checkout, y no hace falta leerlo.
            if path.stat().st_size > 2 * MAX_BYTES:
                reason = "large"
            else:
                data = to_lf(fsutil.read_bytes(path))
                head = data[:_SNIFF]
                if len(data) > MAX_BYTES:
                    reason = "large"
                elif b"\0" in head:
                    reason = "binary"
                elif _generated(head[:512].lower()):
                    reason = "generated"
                else:
                    category = _category(rel, False)
                    result.files.append(
                        SourceFile(
                            rel,
                            len(data),
                            fsutil.sha256_bytes(data),
                            language_of(rel),
                            category,
                            lines=count_lines(data),
                        )
                    )
                    continue
        if reason not in _UNCOUNTED:
            counts[reason] = counts.get(reason, 0) + 1
    result.excluded = dict(sorted(counts.items()))
    result.files.sort(key=lambda f: f.path)
    return result


def has_code(project: Path) -> bool:
    """¿El proyecto ya tiene código propio? Solo mira nombres: no lee ni hashea nada."""
    project = Path(project)
    listed = git.run(project, "ls-files", "-z")
    if listed.ok and listed.out:
        names = [n for n in listed.out.split("\0") if n]
    else:
        names = _walked(project)
    for rel in names:
        pure = PurePosixPath(rel)
        if pure.parts[0] == _meta.PROJECT_DIR or any(p in VENDORED_DIRS for p in pure.parts[:-1]):
            continue
        if language_of(rel) in CODE_LANGUAGES and not is_test(rel):
            return True
    return False
