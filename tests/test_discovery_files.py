    paths = [f.path for f in found.files]
    assert paths == sorted(paths)
    assert paths == [
        ".env",
        ".env.example",
        "README.md",
        "api/migrations/001_init.js",
        "docs/adr/0001-use-fastapi.md",
        "src/app/__init__.py",
        "src/app/main.py",
        "tests/test_main.py",
        "web/src/App.test.tsx",
        "web/src/App.tsx",
    ]
    assert found.git is True
